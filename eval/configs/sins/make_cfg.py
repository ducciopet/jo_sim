#!/usr/bin/env python3
"""
Build a per-dataset SINS profile sins/cfg/<dataset>/ from a base profile (cfg/outdoor by default) plus the few
dataset-specific values in eval/configs/sins/<dataset>/overrides.yaml (sensor setup, range, YOLO classes).
Everything else is the base profile verbatim, so tuning the base reaches every dataset built on it.

Line-based: each overridden `key: value` line keeps its indentation and comment, and is tagged `# <dataset>`;
a key the base file lacks is added at the top of its node's ros__parameters. Run with `env:=<dataset>`.

overrides.yaml:   base: outdoor
                  files:
                    preprocessing.yaml:
                      preprocessing_node: {lidar_range_x: 25.0, camera_names: [front_camera]}
usage: make_cfg.py <dataset>      (then rebuild/install sins so the launch file finds cfg/<dataset>)
"""
import json
import re
import shutil
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[3]


def fmt(v):
    return json.dumps(v) if isinstance(v, (list, str, dict)) else ('true' if v is True else 'false' if v is False else str(v))


def apply(text, node, overrides, tag):
    lines = text.split('\n')
    start = next((i for i, l in enumerate(lines) if re.match(rf'^{re.escape(node)}:\s*$', l)), None)
    if start is None:
        raise SystemExit(f'node {node} not found')
    end = next((i for i in range(start + 1, len(lines)) if re.match(r'^\S', lines[i]) and not lines[i].startswith('#')),
               len(lines))
    params = next(i for i in range(start, end) if lines[i].strip() == 'ros__parameters:')
    for key, val in overrides.items():
        hit = [i for i in range(params, end) if re.match(rf'^\s+{re.escape(key)}:', lines[i])]
        if len(hit) > 1:
            raise SystemExit(f'{node}.{key} appears {len(hit)} times')
        if hit:
            m = re.match(rf'^(\s+{re.escape(key)}:\s*)([^#]*?)(\s*#.*)?$', lines[hit[0]])
            lines[hit[0]] = f'{m.group(1).rstrip()} {fmt(val)}  # {tag} (base: {m.group(2).strip()}){(m.group(3) or "").rstrip()}'
            # a block-style mapping in the base (children indented below the key) is replaced as a whole
            ind = len(lines[hit[0]]) - len(lines[hit[0]].lstrip())
            j = hit[0] + 1
            while j < end and lines[j].strip() and len(lines[j]) - len(lines[j].lstrip()) > ind:
                j += 1
            if j > hit[0] + 1:
                del lines[hit[0] + 1:j]
                end -= j - hit[0] - 1
        else:
            lines.insert(params + 1, f'    {key}: {fmt(val)}  # {tag} (not in base)')
            end += 1
    return '\n'.join(lines)


def main():
    ds = sys.argv[1]
    spec = yaml.safe_load(open(REPO / 'eval/configs/sins' / ds / 'overrides.yaml'))
    base = REPO / 'sins/cfg' / spec.get('base', 'outdoor')
    out = REPO / 'sins/cfg' / ds
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(base, out)
    for fname, nodes in (spec.get('files') or {}).items():
        p = out / fname
        text = p.read_text()
        for node, ov in nodes.items():
            text = apply(text, node, ov, ds)
        yaml.safe_load(text)                       # still valid yaml
        p.write_text(text)
    (out / 'GENERATED.md').write_text(
        f'Generated by eval/configs/sins/make_cfg.py {ds} from cfg/{spec.get("base", "outdoor")} + '
        f'eval/configs/sins/{ds}/overrides.yaml. Do not edit here: edit the base profile or the overrides.\n')
    print(f'{out}: {sum(len(o) for n in (spec.get("files") or {}).values() for o in n.values())} overrides')


if __name__ == '__main__':
    main()
